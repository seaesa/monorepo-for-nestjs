// Compiles src → dist (tsc) and generates the platform CSS from src/tokens.ts:
//   dist/web.css    shadcn / Tailwind v4 format  (:root + .dark, @theme inline)
//   dist/native.css Uniwind format               (@layer theme + @variant light/dark)
import { execSync } from 'node:child_process';
import { mkdirSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
execSync('tsc -p tsconfig.json', { cwd: root, stdio: 'inherit' });

const require = createRequire(import.meta.url);
const tokensPath = join(root, 'dist/tokens.js');
delete require.cache[tokensPath];
const { colors, fonts, radius, radiusScale } = require(tokensPath);

const kebab = (key) => key.replace(/([a-z])([A-Z0-9])/g, '$1-$2').toLowerCase();
const header = '/* GENERATED by @repo/theme from src/tokens.ts — do not edit. */\n';
const vars = (scheme, prefix, indent) =>
  Object.entries(colors[scheme])
    .map(([key, value]) => `${indent}--${prefix}${kebab(key)}: ${value};`)
    .join('\n');
const radii = Object.entries(radiusScale)
  .map(([key, factor]) => `  --radius-${key}: calc(var(--radius) * ${factor});`)
  .join('\n');

const web = `${header}
@custom-variant dark (&:is(.dark *));

@theme inline {
${Object.keys(colors.light)
  .map((key) => `  --color-${kebab(key)}: var(--${kebab(key)});`)
  .join('\n')}
${radii}
}

:root {
  --radius: ${radius};
${vars('light', '', '  ')}
}

.dark {
${vars('dark', '', '  ')}
}
`;

// React Native has no font fallbacks: one family name, faces picked by fontWeight
// (the app registers every weight under this name with expo-font).
const native = `${header}
@theme {
  --radius: ${radius};
${radii}
  --font-sans: '${fonts.sans}';
  --font-heading: '${fonts.sans}';
}

@layer theme {
  :root {
    @variant light {
${vars('light', 'color-', '      ')}
    }

    @variant dark {
${vars('dark', 'color-', '      ')}
    }
  }
}
`;

mkdirSync(join(root, 'dist'), { recursive: true });
writeFileSync(join(root, 'dist/web.css'), web);
writeFileSync(join(root, 'dist/native.css'), native);
console.log('@repo/theme: built dist/{index.js,web.css,native.css}');
